#!/usr/bin/env bash
# Refresh each paper's figures/ from ../paper_figs, build both PDFs, and package
# self-contained Overleaf projects plus PDFs into ../deliverables/.
set -e
cd "$(dirname "$0")"
FIGS=../paper_figs
mkdir -p paperA/figures paperB/figures
cp $FIGS/fig1_metric_divergence.pdf $FIGS/fig2_bias_churn.pdf $FIGS/fig3_ranking_inversion.pdf \
   $FIGS/fig4_vams_meanP.pdf $FIGS/fig5_pivotality.pdf paperA/figures/
cp $FIGS/figB1_rule_vs_static.pdf $FIGS/figB2_whitewashing.pdf paperB/figures/
for d in paperA paperB; do
  (cd $d && pdflatex -interaction=nonstopmode main >/dev/null && bibtex main >/dev/null \
     && pdflatex -interaction=nonstopmode main >/dev/null && pdflatex -interaction=nonstopmode main > build.log \
     && ! grep -qE '^!|Overfull|undefined' build.log && echo "$d: $(grep 'Output written' build.log)") \
   || { echo "$d: BUILD PROBLEM, see $d/build.log"; exit 1; }
done
OUT=../deliverables; rm -rf $OUT; mkdir -p $OUT
pack(){ # $1 dir, $2 name
  T=$(mktemp -d); mkdir -p $T/$2
  cp $1/main.tex $1/refs.bib $1/main.bbl $T/$2/
  cp -r $1/figures $T/$2/
  [ -d $1/tables ] && cp -r $1/tables $T/$2/
  (cd $T && zip -qr $2.zip $2)
  mv $T/$2.zip $OUT/; cp -r $T/$2 $OUT/${2}_latex; rm -rf $T
  cp $1/main.pdf $OUT/$2.pdf
}
pack paperA PaperA_ScoreBeforeYouSelect
pack paperB PaperB_OptimismMustDecay
cat > $OUT/README.md <<'TXT'
# Deliverables

| file | what |
|---|---|
| `PaperA_ScoreBeforeYouSelect.pdf` | Paper A, compiled |
| `PaperA_ScoreBeforeYouSelect.zip` | Paper A, self-contained LaTeX project (upload to Overleaf as is) |
| `PaperB_OptimismMustDecay.pdf` | Paper B, compiled |
| `PaperB_OptimismMustDecay.zip` | Paper B, self-contained LaTeX project |
| `*_latex/` | the same projects, unzipped |

**Overleaf:** New Project -> Upload Project -> choose the .zip. Compiler: pdfLaTeX, main
document `main.tex` (Menu). Each project contains `main.tex`, `refs.bib`, `main.bbl`,
`figures/` and, where used, `tables/` (generated by the scripts in `paper/code`; edit the
scripts, not the tables).

**Anonymity:** both papers use `acmart` with `[sigconf,anonymous,review,nonacm]`, which hides
authors and adds line numbers for double-blind review. For a camera-ready or preprint, remove
`anonymous,review`, fill in `\author`/`\affiliation`, and replace the anonymous companion
citation (`companionA` in Paper B's refs.bib) with the real reference.

**Template:** a venue that is not ACM (IJCAI, ICML, ...) needs its own style file; the text,
tables and figures carry over.

Rebuild everything from the results with `paper/build_all.sh`.
TXT
ls -la $OUT
